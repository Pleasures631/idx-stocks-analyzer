CREATE TABLE IF NOT EXISTS t_stockbit_foreign_domestic (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  symbol VARCHAR(20) NOT NULL,
  trade_date DATE NOT NULL,
  market_type VARCHAR(30) NOT NULL DEFAULT 'REGULAR',
  foreign_buy_value BIGINT NOT NULL DEFAULT 0,
  foreign_sell_value BIGINT NOT NULL DEFAULT 0,
  domestic_buy_value BIGINT NOT NULL DEFAULT 0,
  domestic_sell_value BIGINT NOT NULL DEFAULT 0,
  foreign_net_value BIGINT NOT NULL DEFAULT 0,
  domestic_net_value BIGINT NOT NULL DEFAULT 0,
  foreign_buy_volume BIGINT NOT NULL DEFAULT 0,
  foreign_sell_volume BIGINT NOT NULL DEFAULT 0,
  domestic_buy_volume BIGINT NOT NULL DEFAULT 0,
  domestic_sell_volume BIGINT NOT NULL DEFAULT 0,
  foreign_buy_frequency BIGINT NOT NULL DEFAULT 0,
  foreign_sell_frequency BIGINT NOT NULL DEFAULT 0,
  domestic_buy_frequency BIGINT NOT NULL DEFAULT 0,
  domestic_sell_frequency BIGINT NOT NULL DEFAULT 0,
  last_updated VARCHAR(50) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_stockbit_foreign_domestic (symbol, trade_date, market_type),
  KEY idx_stockbit_foreign_domestic_date (trade_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
